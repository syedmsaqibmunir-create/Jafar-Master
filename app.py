import streamlit as st
import datetime
from math import floor

# ابجدِ قمری
abjad_qamari = {
    'ا': 1, 'ب': 2, 'ج': 3, 'د': 4, 'ہ': 5, 'و': 6, 'ز': 7, 'ح': 8, 'ط': 9, 'ی': 10,
    'ک': 20, 'ل': 30, 'م': 40, 'ن': 50, 'س': 60, 'ع': 70, 'ف': 80, 'ص': 90, 'ق': 100,
    'ر': 200, 'ش': 300, 'ت': 400, 'ث': 500, 'خ': 600, 'ذ': 700, 'ض': 800, 'ظ': 900, 'غ': 1000
}

# سات سیارے اور ان کے موکل
saat_list = [
    {"ساعت": "زحل", "موکل": "کسفیائیل"}, {"ساعت": "مشتری", "موکل": "صرفیائیل"},
    {"ساعت": "مریخ", "موکل": "سمسمائیل"}, {"ساعت": "شمس", "موکل": "رقیائیل"},
    {"ساعت": "زہرہ", "موکل": "عنائیل"}, {"ساعت": "عطارد", "موکل": "میخائیل"},
    {"ساعت": "قمر", "موکل": "جبرائیل"}
]

st.title("علمِ جفر گرینڈ ماسٹر (پروفیشنل)")
tabs = st.tabs(["زائچہ", "سوال", "ساعت و موکل", "نقش", "ابجد"])

with tabs[2]: # ساعت و موکل ٹیب
    st.header("ساعت اور موکل کا خودکار حساب")
    
    # دن اور رات کا تعین (آج 31 مئی کے حساب سے)
    now = datetime.datetime.now()
    # سادہ منطق: 06:00 طلوعِ آفتاب فرض کیا گیا ہے
    day_start = now.replace(hour=6, minute=0, second=0)
    
    if now >= day_start:
        # دن کی ساعت
        hours_passed = (now - day_start).total_seconds() / 3600
        saat_idx = int(hours_passed // 1.5) % 7
    else:
        # رات کی ساعت
        hours_passed = (now + datetime.timedelta(hours=18)).total_seconds() / 3600
        saat_idx = int(hours_passed // 1.5) % 7
    
    current_saat = saat_list[saat_idx]
    
    st.subheader(f"موجودہ تاریخ: {now.strftime('%d-%m-%Y')}")
    st.metric("موجودہ ساعت", current_saat["ساعت"])
    st.metric("متعلقہ موکل", current_saat["موکل"])
    
    st.write("---")
    st.write("نوٹ: یہ حساب ہر مہینے کی تاریخ کے مطابق خودکار تبدیل ہوگا۔")

